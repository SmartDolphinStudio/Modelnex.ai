function blocksFor(body: string): DocumentBlock[] {
  return body
    .split(/\n\s*\n/)
    .map((chunk) => chunk.trim())
    .filter(Boolean)
    .map((chunk): DocumentBlock => {
      const lines = chunk.split("\n");
      if (lines.every((line) => line.startsWith("- "))) {
        return { type: "list", items: lines.map((line) => line.slice(2)) };
      }
      if (lines.every((line) => /^\d+\.\s/.test(line))) {
        return {
          type: "list",
          items: lines.map((line) => line.replace(/^\d+\.\s/, "")),
        };
      }
      if (lines.every((line) => line.includes("|"))) {
        const rows = lines.map((line) =>
          line.split("|").map((cell) => cell.trim()),
        );
        return { type: "matrix", headers: rows[0], rows: rows.slice(1) };
      }
      return { type: "paragraph", text: lines.join(" ") };
    });
}

