import type { DocumentBlock, ProductIntroductionDocument } from "./productIntroduction";

type Article = ProductIntroductionDocument;

const paragraphs = (...text: string[]): DocumentBlock[] =>
  text.map((value) => ({ type: "paragraph", text: value }));

const list = (...items: string[]): DocumentBlock => ({ type: "list", items });

const heading = (id: string, text: string): DocumentBlock => ({
  type: "heading",
  id,
  text,
});

const table = (text: string): DocumentBlock => {
  const rows = text.split("\n").map((line) =>
    line.split("|").map((cell) => cell.trim()),
  );
  return { type: "matrix", headers: rows[0], rows: rows.slice(1) };
};

